class ThesisBuilder:
    def __init__(self) -> None:
        self.doc = Document()
        self.figure_counters: dict[int, int] = {}
        self.table_counters: dict[int, int] = {}
        self.citation_counter = 1
        self._setup_document()

    def _setup_document(self) -> None:
        section = self.doc.sections[0]
        section.left_margin = Mm(25)
        section.right_margin = Mm(10)
        section.top_margin = Mm(20)
        section.bottom_margin = Mm(20)

        styles = self.doc.styles
        styles["Normal"].font.name = "Times New Roman"
        styles["Normal"]._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        styles["Normal"].font.size = Pt(14)

    def _set_paragraph_format(self, p, indent: bool = True, align=WD_ALIGN_PARAGRAPH.JUSTIFY) -> None:
        pf = p.paragraph_format
        pf.line_spacing = 1.5
        pf.first_line_indent = Cm(1.25) if indent else Cm(0)
        pf.space_before = Pt(0)
        pf.space_after = Pt(0)
        p.alignment = align

    def add_paragraph(
        self,
        text: str,
        indent: bool = True,
        align=WD_ALIGN_PARAGRAPH.JUSTIFY,
        bold: bool = False,
        cite: bool = False,
    ) -> None:
        p = self.doc.add_paragraph()
        self._set_paragraph_format(p, indent=indent, align=align)
        if cite and self.citation_counter <= len(REFERENCES):
            text = f"{text} [{self.citation_counter}]"
            self.citation_counter += 1
        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        run.font.size = Pt(14)
        run.bold = bold

    def add_heading_like(self, text: str, centered: bool = False, uppercase: bool = False) -> None:
        p = self.doc.add_paragraph()
        self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER if centered else WD_ALIGN_PARAGRAPH.LEFT)
        pf = p.paragraph_format
        pf.space_before = Pt(18)
        pf.space_after = Pt(12)
        run = p.add_run(text.upper() if uppercase else text)
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        run.font.size = Pt(14)
        run.bold = True

    def add_page_break(self) -> None:
        self.doc.add_page_break()

    def add_table(self, title: str, headers: list[str], rows: list[list[str]], chapter: int) -> None:
        self.table_counters[chapter] = self.table_counters.get(chapter, 0) + 1
        num = self.table_counters[chapter]
        cap = self.doc.add_paragraph()
        self._set_paragraph_format(cap, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
        run = cap.add_run(f"Таблица {chapter}.{num} – {title}")
        run.bold = True
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        run.font.size = Pt(14)

        table = self.doc.add_table(rows=1, cols=len(headers))
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.style = "Table Grid"
        hdr = table.rows[0].cells
        for idx, header in enumerate(headers):
            hdr[idx].text = header
        for row in rows:
            cells = table.add_row().cells
            for idx, value in enumerate(row):
                cells[idx].text = value
        for row in table.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT)
                    for run in p.runs:
                        run.font.name = "Times New Roman"
                        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
                        run.font.size = Pt(12)
        self.add_paragraph("")

    def add_small_table(self, title: str, headers: list[str], rows: list[list[str]]) -> None:
        self.add_heading_like(title, centered=True)
        table = self.doc.add_table(rows=1, cols=len(headers))
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.style = "Table Grid"
        for idx, header in enumerate(headers):
            table.rows[0].cells[idx].text = header
        for row in rows:
            cells = table.add_row().cells
            for idx, value in enumerate(row):
                cells[idx].text = value
        for row in table.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT)
                    for run in p.runs:
                        run.font.name = "Times New Roman"
                        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
                        run.font.size = Pt(10.5)

    def add_listing(self, title: str, lines: list[str]) -> None:
        self.add_heading_like(title)
        table = self.doc.add_table(rows=1, cols=1)
        table.style = "Table Grid"
        cell = table.cell(0, 0)
        cell.text = ""
        p = cell.paragraphs[0]
        self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT)
        p.paragraph_format.line_spacing = 1.0
        for idx, line in enumerate(lines):
            if idx:
                p.add_run("\n")
            run = p.add_run(line)
            run.font.name = "Courier New"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Courier New")
            run.font.size = Pt(10.5)
        self.add_paragraph("")

    def add_figure(self, chapter: int, title: str, image_path: Path, width_cm: float = 16.0) -> None:
        self.figure_counters[chapter] = self.figure_counters.get(chapter, 0) + 1
        num = self.figure_counters[chapter]
        p = self.doc.add_paragraph()
        self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
        run = p.add_run()
        run.add_picture(str(image_path), width=Cm(width_cm))
        cap = self.doc.add_paragraph()
        self._set_paragraph_format(cap, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
        r = cap.add_run(f"Рисунок {chapter}.{num} – {title}")
        r.font.name = "Times New Roman"
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        r.font.size = Pt(14)

    def add_toc(self) -> None:
        p = self.doc.add_paragraph()
        self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT)
        r = p.add_run()
        fld_begin = OxmlElement("w:fldChar")
        fld_begin.set(qn("w:fldCharType"), "begin")
        instr = OxmlElement("w:instrText")
        instr.set(qn("xml:space"), "preserve")
        instr.text = r'TOC \o "1-3" \h \z \u'
        fld_sep = OxmlElement("w:fldChar")
        fld_sep.set(qn("w:fldCharType"), "separate")
        fld_text = OxmlElement("w:t")
        fld_text.text = "Оглавление будет сформировано в Word при обновлении полей."
        fld_sep.append(fld_text)
        fld_end = OxmlElement("w:fldChar")
        fld_end.set(qn("w:fldCharType"), "end")
        r._r.append(fld_begin)
        r._r.append(instr)
        r._r.append(fld_sep)
        r._r.append(fld_end)

    def add_page_number(self, section) -> None:
        header = section.header
        p = header.paragraphs[0]
        self._set_paragraph_format(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
        r = p.add_run()
        fld_begin = OxmlElement("w:fldChar")
        fld_begin.set(qn("w:fldCharType"), "begin")
        instr = OxmlElement("w:instrText")
        instr.set(qn("xml:space"), "preserve")
        instr.text = " PAGE "
        fld_end = OxmlElement("w:fldChar")
        fld_end.set(qn("w:fldCharType"), "end")
        r._r.append(fld_begin)
        r._r.append(instr)
        r._r.append(fld_end)

