    def build(self) -> None:
        self.add_title_page()

        sec2 = self.doc.add_section(WD_SECTION_START.NEW_PAGE)
        sec2.left_margin = Mm(25)
        sec2.right_margin = Mm(10)
        sec2.top_margin = Mm(20)
        sec2.bottom_margin = Mm(20)
        self.add_assignment_page()

        sec3 = self.doc.add_section(WD_SECTION_START.NEW_PAGE)
        sec3.left_margin = Mm(25)
        sec3.right_margin = Mm(10)
        sec3.top_margin = Mm(20)
        sec3.bottom_margin = Mm(20)
        self.add_page_number(sec3)

        self.add_heading_like("Содержание", centered=True, uppercase=True)
        self.add_toc()

        self.add_page_break()
        self.add_heading_like("Реферат", centered=True, uppercase=True)
        for p in ABSTRACT_TEXT:
            self.add_paragraph(p)

        self.add_page_break()
        self.add_heading_like("Введение", centered=True, uppercase=True)
        for p in INTRO_TEXT:
            self.add_paragraph(p, cite=True)

        for chapter_idx, chapter in enumerate(CHAPTERS, start=1):
            self.add_page_break()
            self.add_heading_like(chapter["title"], centered=True)
            if chapter_idx == 1:
                self.add_paragraph(
                    "В главе приведены результаты анализа предметной области, обзор практик интернет-торговли и формализация требований к системе на основе фактических возможностей проекта DinoJelly.",
                    indent=True,
                )
                self.add_figure(1, "Общая архитектурная схема рассматриваемой системы", DIAGRAMS / "01_architecture.png", 15.5)
            if chapter_idx == 2:
                self.add_paragraph(
                    "Во второй главе рассматриваются архитектурные решения, технологический стек, модель данных и инфраструктурный контур проекта.",
                    indent=True,
                )
